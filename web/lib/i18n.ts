export const TRANSLATIONS: Record<Language, Dict> = { uz, en, ru };

export function translate(language: Language, key: string, vars?: Record<string, string | number>): string {
  let text = TRANSLATIONS[language][key] ?? TRANSLATIONS.uz[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`{{${k}}}`, "g"), String(v));
    }
  }
  return text;
}
